def app_file(name):
    """A Bayside app file as it was at the Week 15 checkpoint."""
    return read(APP + name, REV)


def app_function(name):
    """One top-level function of database.py at the checkpoint, exactly as written."""
    return function(APP + "database.py", name, REV)


def app_test(name):
    """One test of tests/test_database.py at the checkpoint, exactly as written."""
    return function(APP + "tests/test_database.py", name, REV)


def app_part(name):
    """One part of app.py at the checkpoint, exactly as written."""
    lines = app_file("app.py").split("\n")
    names = list(APP_PARTS)
    start = next(i for i, line in enumerate(lines) if APP_PARTS[name] in line)
    end = len(lines)
    if names.index(name) + 1 < len(names):
        after = APP_PARTS[names[names.index(name) + 1]]
        end = next(i for i in range(start, len(lines)) if after in lines[i])
    return "\n".join(lines[start:end]).rstrip()


