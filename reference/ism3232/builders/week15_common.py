def start(code):
    """A Streamlit test-tool run of code, after its first run."""
    from streamlit.testing.v1 import AppTest

    app = AppTest.from_string(code, default_timeout=30)
    app.run()
    return app


def finished(app):
    if app.exception:
        raise RuntimeError(app.exception[0].message)
    return app


def counter_after_clicks(code, clicks):
    """What a counter app shows after its first button is clicked `clicks` times."""
    app = start(code)
    for _ in range(clicks):
        app.button[0].click().run()
    return "\n".join(element.value for element in finished(app).markdown)


def echo_bubbles(code, messages):
    """The chat bubbles an echo app shows after each message is typed, one per line."""
    app = start(code)
    for message in messages:
        app.chat_input[0].set_value(message).run()
    return "\n".join(
        f"{bubble.name}: {bubble.markdown[0].value}"
        for bubble in finished(app).chat_message
    )


def with_clicks(code, clicks, shown):
    """The slide convention: the code, a blank line, then what the page shows."""
    lines = "\n".join(f"# {line}" for line in shown.split("\n"))
    return f"{code.rstrip()}\n\n# After {clicks} clicks the page shows:\n{lines}"


