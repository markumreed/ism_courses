def session_steps():
    """The saved browser session, section name -> text, exactly as captured."""
    steps, name = {}, None
    for line in (RUNS / "session.txt").read_text().split("\n"):
        if line.startswith("## "):
            name = line[3:]
            steps[name] = []
        elif name is not None:
            steps[name].append(line)
    return {key: "\n".join(lines).strip("\n") for key, lines in steps.items()}


